#!/usr/bin/env python3
"""Build a compact, manifest-ID keyed lookup directory from the supplied CSV/ZIP.

Only title, unverified listed author, category and source filename are stored.
Search URLs are generated by the application from the matched record identity.
The script never changes the primary book catalog or source ebook files.
"""

from __future__ import annotations

import argparse
import collections
import csv
import gzip
import json
import sys
import zipfile
from datetime import datetime, timezone
from pathlib import Path

REQUIRED_HEADERS = [
    "Manifest ID",
    "Listed title",
    "Listed author / contributor (unverified)",
    "Listed category",
    "Source filename",
    "Link status",
]

def open_csv(path: Path):
    if path.suffix.lower() == ".zip":
        archive = zipfile.ZipFile(path)
        candidates = [name for name in archive.namelist() if name.lower().endswith(".csv")]
        if len(candidates) != 1:
            archive.close()
            raise ValueError(f"Expected exactly one CSV in ZIP; found {len(candidates)}")
        raw = archive.open(candidates[0], "r")
        import io
        return archive, io.TextIOWrapper(raw, encoding="utf-8-sig", newline=""), candidates[0]
    return None, path.open("r", encoding="utf-8-sig", newline=""), str(path)

def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("input", type=Path, help="CSV or ZIP containing one CSV")
    parser.add_argument(
        "--output",
        type=Path,
        default=Path("data/catalog/research_link_directory.json.gz"),
        help="Compressed JSON output path",
    )
    parser.add_argument(
        "--report",
        type=Path,
        default=Path("data/reports/research_link_directory_build.json"),
        help="JSON build summary path",
    )
    parser.add_argument("--expected-rows", type=int, default=86260)
    args = parser.parse_args()

    if not args.input.is_file():
        parser.error(f"Input file not found: {args.input}")

    archive = None
    source = None
    ids: set[int] = set()
    duplicate_ids: list[int] = []
    status_counts: collections.Counter[str] = collections.Counter()
    group_counts: collections.Counter[str] = collections.Counter()
    row_count = 0
    min_id = None
    max_id = None

    try:
        archive, source, member = open_csv(args.input)
        reader = csv.DictReader(source)
        headers = reader.fieldnames or []
        missing = [h for h in REQUIRED_HEADERS if h not in headers]
        if missing:
            raise ValueError("Missing required columns: " + ", ".join(missing))

        args.output.parent.mkdir(parents=True, exist_ok=True)
        # Stream output to keep memory use low for the 86k directory.
        with gzip.open(args.output, "wt", encoding="utf-8", newline="") as output:
            output.write('{"version":1,"records":[')
            first = True
            for row_number, row in enumerate(reader, start=2):
                row_count += 1
                raw_id = (row.get("Manifest ID") or "").strip()
                try:
                    manifest_id = int(raw_id)
                except ValueError as exc:
                    raise ValueError(f"Invalid Manifest ID at CSV row {row_number}: {raw_id!r}") from exc

                if manifest_id in ids:
                    duplicate_ids.append(manifest_id)
                ids.add(manifest_id)
                min_id = manifest_id if min_id is None else min(min_id, manifest_id)
                max_id = manifest_id if max_id is None else max(max_id, manifest_id)

                title = (row.get("Listed title") or "").strip()
                author = (row.get("Listed author / contributor (unverified)") or "").strip()
                category = (row.get("Listed category") or "").strip()
                filename = (row.get("Source filename") or "").strip()
                status = (row.get("Link status") or "").strip()

                key = "|".join((title.casefold(), author.casefold(), category.casefold()))
                group_counts[key] += 1
                status_counts[status] += 1

                record = {
                    "manifestId": manifest_id,
                    "listedTitle": title,
                    "listedAuthor": author,
                    "listedAuthorVerified": False,
                    "listedCategory": category,
                    "sourceFilename": filename,
                    "linkStatus": "LOOKUP_LINKS_NOT_VERIFIED",
                    "sourceLinkStatus": status,
                }
                if not first:
                    output.write(",")
                json.dump(record, output, ensure_ascii=False, separators=(",", ":"))
                first = False
            output.write("]}")

        repeated_groups = sum(1 for count in group_counts.values() if count > 1)
        rows_in_repeated_groups = sum(count for count in group_counts.values() if count > 1)
        report = {
            "generatedAt": datetime.now(timezone.utc).isoformat(),
            "input": str(args.input),
            "csvMember": member,
            "output": str(args.output),
            "rows": row_count,
            "uniqueManifestIds": len(ids),
            "minManifestId": min_id,
            "maxManifestId": max_id,
            "duplicateManifestIdCount": len(duplicate_ids),
            "duplicateManifestIdSamples": duplicate_ids[:50],
            "expectedRows": args.expected_rows,
            "rowCountMatchesExpected": row_count == args.expected_rows,
            "uniqueTitleAuthorCategoryGroups": len(group_counts),
            "repeatedTitleAuthorCategoryGroups": repeated_groups,
            "rowsInRepeatedGroups": rows_in_repeated_groups,
            "extraRowsInRepeatedGroups": rows_in_repeated_groups - repeated_groups,
            "sourceLinkStatusCounts": dict(status_counts),
            "notes": [
                "Listed author/contributor fields remain explicitly unverified.",
                "Search links are generated by the app and remain unverified research leads.",
                "No actual cover image, ISBN, edition, current retail price, free-download right or redistribution licence is inferred.",
                "Repeated title/author/category groups are not automatically deleted; editions and source files may differ.",
                "The source CSV is never modified and is not copied into the application catalog.",
            ],
        }
        args.report.parent.mkdir(parents=True, exist_ok=True)
        args.report.write_text(json.dumps(report, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        print(json.dumps(report, ensure_ascii=False, indent=2))
        print(f"\nWrote compressed directory: {args.output}")
        print(f"Wrote report: {args.report}")
        if duplicate_ids:
            return 2
        return 0 if row_count == args.expected_rows else 3

    except (OSError, zipfile.BadZipFile, ValueError) as exc:
        print(f"Build failed: {exc}", file=sys.stderr)
        return 1
    finally:
        if source is not None:
            source.close()
        if archive is not None:
            archive.close()

if __name__ == "__main__":
    raise SystemExit(main())
